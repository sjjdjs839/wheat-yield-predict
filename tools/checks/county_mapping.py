def map_weather_to_yield(city, weather_name):
    """将气象文件名映射为产量标签区县名。返回 None 表示跳过。"""
    key = (city, weather_name)
    if key in COUNTY_MAP:
        return COUNTY_MAP[key]
    return weather_name  # 没在映射表中的，默认同名


def should_skip_yield(city, county):
    """判断产量标签中的区县是否不需要气象数据。"""
    return (city, county) in SKIP_YIELD_COUNTIES
